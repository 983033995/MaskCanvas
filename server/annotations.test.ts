import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { createApp } from './app.js';
import { createStore } from './store.js';
import { exportAnnotations, importAnnotations } from './annotations.js';

test('annotations JSON round-trips geometry without image data or accepting edits', async () => {
  const store = createStore({ dataDir: await mkdtemp(path.join(os.tmpdir(), 'maskcanvas-json-')) });
  const png = await sharp({ create: { width: 20, height: 16, channels: 4, background: '#567' } }).png().toBuffer();
  let p = await store.createProject({ name: 'JSON test', imageDataUrl: `data:image/png;base64,${png.toString('base64')}` });
  const blank = await exportAnnotations(store, p.id);
  const document = structuredClone(blank);
  document.regions = [{ id: 'r1', name: '精修建议', kind: 'edit', intent: '自然修饰', feather: 1, context: { x: 0, y: 0, width: 12, height: 12 }, shapes: [{ type: 'rect', x: 1, y: 2, width: 8, height: 9 }, { type: 'brush', points: [{ x: 4, y: 4 }], radius: 1, subtract: true }] }, { id: 'k1', name: '保护', kind: 'keep', intent: '', feather: 0, shapes: [{ type: 'polygon', points: [{ x: 3, y: 4 }, { x: 6, y: 4 }, { x: 4, y: 7 }] }] }];
  p = await importAnnotations(store, p.id, document);
  const json = await exportAnnotations(store, p.id);
  assert.deepEqual(json.regions, document.regions);
  assert.deepEqual(json.regions[0]?.context, { x: 0, y: 0, width: 12, height: 12 });
  assert.equal(json.regions[1]?.context, undefined);
  assert.equal(json.revision, blank.revision + 1);
  assert.equal(json.image.sha256, blank.image.sha256);
  assert.match(json.image.assetUri, /^maskcanvas:\/\/projects\//);
  assert.equal(p.versions.length, 1); assert.equal(p.baseVersionId, blank.baseVersionId);
  assert.ok(!JSON.stringify(json).includes('base64'));
  assert.ok(!JSON.stringify(json).includes(store.dataDir));
  await assert.rejects(importAnnotations(store, p.id, document), /更新/);
  const wrongImage = structuredClone(json); wrongImage.image.sha256 = 'f'.repeat(64);
  await assert.rejects(importAnnotations(store, p.id, wrongImage), /不一致/);
  const wrongUri = structuredClone(json); wrongUri.image.assetUri = 'file:///etc/passwd';
  await assert.rejects(importAnnotations(store, p.id, wrongUri), /不一致/);
  const malformed = structuredClone(json); malformed.regions[0].shapes = [{ type: 'rect', x: 19, y: 0, width: 9, height: 3 }];
  await assert.rejects(importAnnotations(store, p.id, malformed), /边界/);
  const smallContext = structuredClone(json); smallContext.regions[0].context = { x: 1, y: 2, width: 1, height: 1 };
  await assert.rejects(importAnnotations(store, p.id, smallContext), /上下文/);
  const nonFiniteContext = structuredClone(json); Object.assign(nonFiniteContext.regions[0]!.context!, { width: Number.NaN });
  await assert.rejects(importAnnotations(store, p.id, nonFiniteContext), /格式/);
  const unexpectedContextField = structuredClone(json); Object.assign(unexpectedContextField.regions[0]!.context!, { token: 'extra' });
  await assert.rejects(importAnnotations(store, p.id, unexpectedContextField), /格式/);
  await assert.rejects(importAnnotations(store, p.id, { ...json, schemaVersion: 99 }), /schema/);
  assert.equal((await store.getProject(p.id)).revision, json.revision);
});

test('HTTP annotations endpoints use the existing session guard and do not trigger jobs', async t => {
  const store = createStore({ dataDir: await mkdtemp(path.join(os.tmpdir(), 'maskcanvas-json-http-')) });
  const png = await sharp({ create: { width: 8, height: 8, channels: 4, background: '#123' } }).png().toBuffer();
  const project = await store.createProject({ name: 'HTTP JSON', imageDataUrl: `data:image/png;base64,${png.toString('base64')}` });
  const app = createApp({ store, token: 'json-test-token' });
  const server = app.listen(0, '127.0.0.1');
  await new Promise<void>(r => server.once('listening', r)); t.after(() => server.close());
  const base = `http://127.0.0.1:${(server.address() as {port:number}).port}`;
  const url = `${base}/api/projects/${project.id}/annotations`;
  const exported = await fetch(url); assert.equal(exported.status, 200);
  const document = await exported.json();
  assert.match(exported.headers.get('content-type')!, /application\/json/);
  const denied = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ document }) });
  assert.equal(denied.status, 403);
  const imported = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json', 'x-maskcanvas-token': 'json-test-token' }, body: JSON.stringify({ document }) });
  assert.equal(imported.status, 200);
  assert.equal((await imported.json()).versions.length, 1);
  assert.deepEqual(await (await fetch(`${base}/api/jobs`)).json(), []);
});
